import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

const cssPath = join(process.cwd(), 'app/assets/css/main.css')
const css = readFileSync(cssPath, 'utf8')

describe('Sales UI cleanup 1/4: layout shell and CSS tokens', () => {
  it('scans packages/crm-core so its shell classes are generated by Tailwind', () => {
    const match = css.match(/^@source\s+"([^"]+)";/m)
    expect(match, 'main.css needs an @source for packages/crm-core').not.toBeNull()
    const dir = resolve(join(cssPath, '..'), match![1])
    expect(dir).toBe(resolve(process.cwd(), '../packages/crm-core/app'))
    expect(existsSync(join(dir, 'layouts/internal.vue'))).toBe(true)
  })

  it('keeps the @source after the Tailwind import and before the theme', () => {
    expect(css.indexOf('@import "tailwindcss"')).toBeLessThan(css.indexOf('@source'))
    expect(css.indexOf('@source')).toBeLessThan(css.indexOf('@theme'))
  })

  it('keeps the design tokens on the approved scale', () => {
    expect(css).toMatch(/--color-muted:\s*#5c6673/)
    expect(css).toMatch(/--color-canvas:\s*#f3f5f8/)
    expect(css).toMatch(/--color-paper:\s*#ffffff/)
    expect(css).toMatch(/--radius-md:\s*0\.5rem/)
  })

  it('shell components only use spacing classes the scan can see', () => {
    const shell = readFileSync(
      join(process.cwd(), '../packages/crm-core/app/layouts/internal.vue'),
      'utf8',
    )
    expect(shell).toMatch(/px-5 py-5/)
  })
})
